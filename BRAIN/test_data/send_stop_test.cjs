const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const { createRequire } = require("node:module");
const ui = process.argv[2];
const source = fs.readFileSync(path.join(ui, "src/components/MasterShell_(1).jsx"), "utf8");
const sendBody = source.match(/const sendCommand = useCallback\(async \(text\) => \{([\s\S]*?)\n  \}, \[kernel.call, pushLog, pushMessage\]\);/)[1];
const stopBody = source.match(/const stopExecution = useCallback\(async \(\) => \{([\s\S]*?)\n  \}, \[pushLog, pushMessage\]\);/)[1];
const AsyncFunction = Object.getPrototypeOf(async function () {}).constructor;
const sendFn = new AsyncFunction("text", "executionRef", "pushMessage", "setIsProcessing", "kernel", "pushLog", "extractSchema", "setDynamicSchema", "setView", sendBody);
const stopFn = new AsyncFunction("executionRef", "setIsStopping", "window", "setIsProcessing", "setVoiceOn", "pushMessage", "pushLog", stopBody);
const deferred = () => { let resolve, reject; const promise = new Promise((yes, no) => { resolve = yes; reject = no; }); return { promise, resolve, reject }; };

async function main() {
  let processing = false, stopping = false;
  const executionRef = { current: { id: 0, processing: false, stopping: false } };
  const messages = [], logs = [], calls = [];
  const first = deferred(), second = deferred(), stopAck = deferred();
  const kernel = { call: (...args) => { calls.push(args); return calls.length === 1 ? first.promise : second.promise; } };
  const pushMessage = (value) => messages.push(value);
  const pushLog = (value) => logs.push(value);
  const setProcessing = (value) => { processing = value; };
  const send = (text) => sendFn(text, executionRef, pushMessage, setProcessing, kernel, pushLog, () => null, () => {}, () => {});
  const stop = (api) => stopFn(executionRef, (value) => { stopping = value; }, { pywebview: { api } }, setProcessing, () => {}, pushMessage, pushLog);
  const oldRequest = send("primeiro");
  assert.equal(processing, true);
  await send("duplicado");
  assert.equal(calls.length, 1);
  let stopCalls = 0;
  const stoppingRequest = stop({ stop_execution: () => { stopCalls++; return stopAck.promise; } });
  assert.equal(stopping, true);
  assert.equal(processing, true);
  await send("durante parada");
  assert.equal(calls.length, 1);
  stopAck.resolve({ ok: true });
  await stoppingRequest;
  assert.equal(stopCalls, 1);
  assert.equal(processing, false);
  assert.equal(stopping, false);
  const freshRequest = send("novo");
  assert.equal(processing, true);
  first.resolve({ reply: "resposta cancelada" });
  await oldRequest;
  assert.equal(processing, true, "late cancelled reply must not clear the new request");
  assert.equal(messages.some((m) => m.text === "resposta cancelada"), false);
  second.resolve({ reply: "resposta nova" });
  await freshRequest;
  assert.equal(processing, false);
  assert.equal(messages.at(-1).text, "resposta nova");
  executionRef.current.processing = true;
  processing = true;
  await stop({ stop_execution: async () => ({ ok: false, errors: ["not confirmed"] }) });
  assert.equal(processing, true, "failed stop must not pretend to be complete");
  assert.equal(stopping, false);
  assert.equal(logs.at(-1).core, "Stop");

  const req = createRequire(path.join(ui, "package.json"));
  const js = req("esbuild").transformSync(fs.readFileSync(path.join(ui, "src/components/SendStopButton.jsx"), "utf8"), { loader: "jsx", format: "cjs" }).code;
  const component = { exports: {} };
  new Function("require", "module", "exports", js)(req, component, component.exports);
  const Button = component.exports.default;
  const props = { processing: false, stopping: false, onStop: () => {}, children: "send-icon", style: { background: "original" } };
  const idle = Button(props);
  assert.equal(idle.props.type, "submit");
  assert.equal(idle.props["aria-label"], "Enviar");
  assert.equal(idle.props.children, "send-icon");
  const busy = Button({ ...props, processing: true });
  assert.equal(busy.props.type, "button");
  assert.equal(busy.props["aria-label"], "Parar execução");
  assert.equal(busy.props.style.color, "#f87171");
  assert.equal(busy.props.onClick, props.onStop);
  assert.equal(Button({ ...props, processing: true, stopping: true }).props.disabled, true);
  assert.equal(source.includes("<GlobalStop />"), false);
  assert.equal((source.match(/<SendStopButton processing=/g) || []).length, 2);
  for (const name of ["Omnibar", "ChatPanel"]) {
    const start = source.indexOf("function " + name + "(");
    const end = source.indexOf("\n}", start);
    assert.ok(start >= 0 && end > start, name + " must exist");
    assert.ok(source.slice(start, end).includes("<SendStopButton processing="), name + " must retain Send/Stop");
  }
  assert.ok(source.includes("<Hotbar"), "compact mode must use Hotbar");
  console.log("Send/Stop behavior OK");
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
